package dev.notnull

object SpeechText {
    private val fencedCode = Regex("(?s)(```|~~~)[^\\n]*\\n?(.*?)\\1")
    private val inlineCode = Regex("`([^`]*)`")
    private val image = Regex("!\\[([^]]*)]\\([^)]*\\)")
    private val link = Regex("\\[([^]]+)]\\([^)]*\\)")
    private val header = Regex("(?m)^\\s{0,3}#{1,6}\\s*")
    private val blockquote = Regex("(?m)^\\s{0,3}>\\s?")
    private val bullet = Regex("(?m)^\\s*[-*+]\\s+")
    private val unicodeBullet = Regex("(?m)^\\s*[•·▪◦]\\s*")
    private val numbered = Regex("(?m)^\\s*\\d+[.)]\\s+")
    private val horizontalRule = Regex("(?m)^\\s*([-*_=])\\s*(?:\\1\\s*){2,}$")
    private val tableSeparator = Regex("(?m)^\\s*\\|?\\s*:?-{3,}:?\\s*(?:\\|\\s*:?-{3,}:?\\s*)+\\|?\\s*$")
    private val htmlTag = Regex("<[^>]+>")
    private val url = Regex("https?://\\S+")
    private val emphasis = Regex("[*_~]")
    private val emoji = Regex("[\\p{So}\\p{Sk}\\x{1F000}-\\x{1FAFF}]")
    private val invisible = Regex("[\\u200B-\\u200D\\uFEFF\\uFE0E\\uFE0F\\u20E3]")
    private val dash = Regex("\\s*(?:--+|[—–])\\s*")
    private val spacedHyphen = Regex("\\s+-\\s+")
    private val punctuationAfterEnd = Regex("([!?])[,;:]+")
    private val repeatedPunctuation = Regex("([,;:])\\s*[,;:]+")
    private val whitespace = Regex("\\s+")
    private val spaceBeforePunctuation = Regex("\\s+([,.!?;:])")
    private val leadingJunk = Regex("^[\\s,;:]+")
    private val trailingJunk = Regex("[\\s,;:]+$")

    fun sanitize(text: String): String {
        var s = text
        s = s.replace(fencedCode, "$2")
        s = s.replace("```", "")
        s = s.replace("~~~", "")
        s = s.replace(inlineCode, "$1")
        s = s.replace("`", "")
        s = s.replace(image, "$1")
        s = s.replace(link, "$1")
        s = s.replace(htmlTag, "")
        s = s.replace(header, "")
        s = s.replace(blockquote, "")
        s = s.replace(bullet, "")
        s = s.replace(unicodeBullet, "")
        s = s.replace(numbered, "")
        s = s.replace(horizontalRule, "")
        s = s.replace(tableSeparator, "")
        s = s.replace("|", ", ")
        s = s.replace(url, "link")
        s = s.replace(emphasis, "")
        s = s.replace(emoji, "")
        s = s.replace(invisible, "")
        s = s.replace(dash, ", ")
        s = s.replace(spacedHyphen, ", ")
        s = s.replace("…", "...")
        s = s.replace(whitespace, " ")
        s = s.replace(spaceBeforePunctuation, "$1")
        s = s.replace(punctuationAfterEnd, "$1")
        s = s.replace(repeatedPunctuation, "$1")
        s = s.replace(leadingJunk, "")
        s = s.replace(trailingJunk, "")
        return s.trim()
    }
}
